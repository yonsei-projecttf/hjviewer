def cargo_lock(*packages, version=4):
    """A Cargo.lock of (name, version, source or None) packages."""
    out = ["# This file is automatically @generated by Cargo.", f"version = {version}", ""]
    for name, ver, source in packages:
        out += ["[[package]]", f'name = "{name}"', f'version = "{ver}"']
        if source:
            out.append(f'source = "{source}"')
        out.append("")
    return "\n".join(out)


