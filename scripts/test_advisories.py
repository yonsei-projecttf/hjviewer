def record(vid, name, fixed=(), aliases=(), ecosystem="crates.io", informational=None, summary="", withdrawn=None):
    """An OSV record of <vid> for the package <name>."""
    events = [{"introduced": "0"}] + [{"fixed": f} for f in fixed]
    affected = {"package": {"name": name, "ecosystem": ecosystem}, "ranges": [{"type": "SEMVER", "events": events}]}
    if informational:
        affected["database_specific"] = {"informational": informational}
    rec = {"id": vid, "aliases": list(aliases), "summary": summary, "affected": [affected]}
    if withdrawn:
        rec["withdrawn"] = withdrawn
    return rec


class FakeOsv:
    """OSV's batch query and records from <db> {(ecosystem, name, version): [IDs]} and <recs>."""

    def __init__(self, db=None, recs=None, page=None):
        self.db = db or {}
        self.recs = recs or {}
        # IDs per package to hand out a page at a time (next_page_token), when set
        self.page = page
        self.queries = []
        self.asked = []

    def querybatch(self, queries):
        self.queries.append(queries)
        results = []
        for q in queries:
            key = (q["package"]["ecosystem"], q["package"]["name"], q["version"])
            ids = self.db.get(key, [])
            if self.page:
                start = int(q.get("page_token", "0"))
                part = ids[start:start + self.page]
                result = {"vulns": [{"id": i, "modified": "2026-11-10T00:00:00Z"} for i in part]} if part else {}
                if start + self.page < len(ids):
                    result["next_page_token"] = str(start + self.page)
                results.append(result)
            else:
                results.append({"vulns": [{"id": i, "modified": "2026-11-10T00:00:00Z"} for i in ids]} if ids else {})
        return {"results": results}

    def vuln(self, vid):
        self.asked.append(vid)
        return self.recs[vid]


class _Socket:
    """What http.client.HTTPResponse reads an answer from: <raw> bytes as a server sent them."""

    def __init__(self, raw):
        self.raw = raw

    def makefile(self, mode, *args, **kwargs):
        return io.BytesIO(self.raw)


def http_answer(raw):
    """urlopen's answer when the server sent <raw>: read as urllib reads it (http.client)."""
    def urlopen(*args, **kwargs):
        r = http.client.HTTPResponse(_Socket(raw))
        r.begin()
        return r
    return urlopen


