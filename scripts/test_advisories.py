class LockFiles(NoNetwork):
    def test_cargo_lock_4_takes_crates_io_only(self):
        text = cargo_lock(
            ("hjv-api", "0.1.0", None),  # the workspace's own crate: a path source
            ("rustls", "0.23.45", CRATES_IO),
            ("serde", "1.0.200", "sparse+https://index.crates.io/"),
            ("tokio-tungstenite", "0.17.1", "git+https://github.com/rustdesk-org/tokio-tungstenite?branch=x#0123abc"),
            ("internal", "1.0.0", "registry+https://registry.example.org/index"),
            ("rustls", "0.21.12", CRATES_IO),
        )
        self.assertEqual(adv.cargo_packages(text), [("rustls", "0.21.12"), ("rustls", "0.23.45"), ("serde", "1.0.200")])

    def test_cargo_lock_3(self):
        text = cargo_lock(("anyhow", "1.0.57", CRATES_IO), ("hbbs", "1.1.14", None), version=3)
        self.assertEqual(adv.cargo_packages(text), [("anyhow", "1.0.57")])

    def test_cargo_lock_with_checksums_and_dependencies(self):
        text = cargo_lock(version=4) + "\n".join([
            "[[package]]", 'name = "base64"', 'version = "0.22.1"', f'source = "{CRATES_IO}"',
            'checksum = "72b3254f16251a8381aa12e40e3c4d2f0199f8c6508fbecb9d91f575e0fbb8c6"',
            "dependencies = [", ' "serde",', "]", ""])
        self.assertEqual(adv.cargo_packages(text), [("base64", "0.22.1")])

    def test_a_broken_cargo_lock_is_an_input_error(self):
        with self.assertRaises(adv.InputError):
            adv.cargo_packages("[[package]\nname = 1", "x/Cargo.lock")
        with self.assertRaises(adv.InputError):
            adv.cargo_packages('[[package]]\nname = "a"\n', "x/Cargo.lock")

    def test_a_cargo_lock_without_packages_is_an_input_error(self):
        # every real one lists its root package: this is a cut or emptied file, not a clean one
        for text in ("", "# This file is automatically @generated by Cargo.\nversion = 4\n"):
            with self.assertRaises(adv.InputError):
                adv.cargo_packages(text, "x/Cargo.lock")

    def test_pubspec_takes_packages_hosted_on_pub_dev_only(self):
        self.assertEqual(adv.pub_packages(PUBSPEC), [("http", "0.13.0"), ("path_provider", "2.1.3")])

    def test_a_pubspec_without_packages_is_an_input_error(self):
        with self.assertRaises(adv.InputError):
            adv.pub_packages("sdks:\n  dart: \">=3.3.0\"\n")


class Advisories(NoNetwork):
    def test_one_advisory_under_several_ids_is_one_line_named_by_rustsec(self):
        recs = {
            "GHSA-aaaa-bbbb-cccc": record("GHSA-aaaa-bbbb-cccc", "rustls", ["0.23.46"],
                                          aliases=["CVE-2026-1", "RUSTSEC-2026-0001"], summary="GitHub's words"),
            "RUSTSEC-2026-0001": record("RUSTSEC-2026-0001", "rustls", ["0.23.46"],
                                        aliases=["GHSA-aaaa-bbbb-cccc"], summary="RustSec's words"),
            "RUSTSEC-2026-0002": record("RUSTSEC-2026-0002", "rustls", ["0.23.46", "0.24.0-dev.2"]),
        }
        got = adv.group("crates.io", "rustls", "0.23.45", sorted(recs), recs)
        self.assertEqual([g["id"] for g in got], ["RUSTSEC-2026-0001", "RUSTSEC-2026-0002"])
        self.assertEqual(got[0]["ids"], {"RUSTSEC-2026-0001", "GHSA-aaaa-bbbb-cccc", "CVE-2026-1"})
        self.assertEqual(got[0]["summary"], "RustSec's words")
        # a pre-release fix only for a pre-release
        self.assertEqual(got[1]["fixed"], ["0.23.46"])
        self.assertEqual(adv.group("crates.io", "rustls", "0.24.0-dev.1", ["RUSTSEC-2026-0002"], recs)[0]["fixed"],
                         ["0.23.46", "0.24.0-dev.2"])
        text = adv.line("FAIL", "server/api/Cargo.lock", "rustls", "0.23.45", got[0])
        self.assertEqual(text, "FAIL server/api/Cargo.lock rustls 0.23.45 RUSTSEC-2026-0001 "
                               "(GHSA-aaaa-bbbb-cccc, CVE-2026-1); fixed in 0.23.46: RustSec's words")

    def test_fixed_versions_sort_as_numbers(self):
        recs = {"RUSTSEC-2026-0386": record("RUSTSEC-2026-0386", "tokio", ["1.53.3", "1.9.1", "1.51.6"])}
        self.assertEqual(adv.group("crates.io", "tokio", "1.53.2", list(recs), recs)[0]["fixed"],
                         ["1.9.1", "1.51.6", "1.53.3"])

    def test_withdrawn_records_count_for_nothing(self):
        recs = {"RUSTSEC-2026-0009": record("RUSTSEC-2026-0009", "a", withdrawn="2026-11-01T00:00:00Z")}
        self.assertEqual(adv.group("crates.io", "a", "1.0.0", list(recs), recs), [])

    def test_informational_only_when_every_record_says_so(self):
        recs = {
            "RUSTSEC-2024-0375": record("RUSTSEC-2024-0375", "atty", informational="unmaintained"),
            "RUSTSEC-2021-0145": record("RUSTSEC-2021-0145", "atty", aliases=["GHSA-g98v-hv3f-hcfr"]),
            "GHSA-g98v-hv3f-hcfr": record("GHSA-g98v-hv3f-hcfr", "atty", aliases=["RUSTSEC-2021-0145"]),
        }
        got = {g["id"]: g for g in adv.group("crates.io", "atty", "0.2.14", sorted(recs), recs)}
        self.assertEqual(got["RUSTSEC-2024-0375"]["kind"], "unmaintained")
        self.assertIsNone(got["RUSTSEC-2021-0145"]["kind"])
        self.assertIn("no fixed version", adv.line("INFO", "l", "atty", "0.2.14", got["RUSTSEC-2024-0375"]))


