    def test_pages_without_end_are_exit_3(self):
        class Endless(FakeOsv):
            def querybatch(self, queries):
                self.queries.append(queries)
                return {"results": [{"vulns": [{"id": "RUSTSEC-2026-0001"}], "next_page_token": "again"}
                                    for _ in queries]}

        osv = Endless()
