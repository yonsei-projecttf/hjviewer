    def write(self, rel, text):
        path = os.path.join(self.root, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)

    def run_check(self, *args, osv=None):
        out, err = io.StringIO(), io.StringIO()
        osv = osv or FakeOsv(self.db, self.recs)
        with mock.patch("sys.stdout", out), redirect_stderr(err):
            status = adv.main(["--root", self.root, *args], osv=osv)
        return status, out.getvalue(), err.getvalue(), osv

    def lines(self, out, tag):
        return [ln for ln in out.splitlines() if ln.split(" ", 1)[0] == tag]

    def test_our_advisories_fail_and_informational_ones_are_listed(self):
        status, out, _, osv = self.run_check()
        self.assertEqual(status, adv.FINDINGS)
        fails = self.lines(out, "FAIL")
        self.assertEqual(len(fails), 2, out)
        self.assertTrue(fails[0].startswith("FAIL server/api/Cargo.lock rustls 0.23.45 RUSTSEC-2026-0346 "
                                            "(GHSA-c8m5-c952-6cm4); fixed in 0.23.46"), fails)
        # unsound is no informational kind here: a failure
        self.assertTrue(fails[1].startswith("FAIL tools/hjv-probe/Cargo.lock tokio 1.53.2 RUSTSEC-2026-0386 unsound"))
        self.assertIn("INFO server/api/Cargo.lock paste 1.0.15 RUSTSEC-2024-0436 unmaintained; no fixed version",
                      out)
        self.assertIn("skipped upstream/rustdesk/Cargo.lock: not fetched", out)
        self.assertIn("read upstream/rustdesk/flutter/pubspec.lock: 2 pub.dev packages", out)
        # OSV hears the names, versions and ecosystems of registry packages only
        sent = [q for batch in osv.queries for q in batch]
        self.assertTrue(all(set(q) == {"package", "version"} and set(q["package"]) == {"name", "ecosystem"}
                            for q in sent))
        names = {q["package"]["name"] for q in sent}
        self.assertNotIn("hjv-api", names)
        self.assertNotIn("window_manager", names)
        self.assertNotIn("private_pkg", names)
        # each record once, though two lock files could name it
        self.assertEqual(len(osv.asked), len(set(osv.asked)))

